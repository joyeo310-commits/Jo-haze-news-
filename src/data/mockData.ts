export function getStatusBand(psi: number): StatusBandInfo {
  if (psi <= 50) return STATUS_BANDS[1];
  if (psi <= 100) return STATUS_BANDS[2];
  if (psi <= 200) return STATUS_BANDS[3];
  if (psi <= 300) return STATUS_BANDS[4];
  return STATUS_BANDS[5];
}

export function getPm25StatusBand(pm25: number): StatusBandInfo {
  if (pm25 <= 12) return STATUS_BANDS[1];
  if (pm25 <= 55) return STATUS_BANDS[2];
  if (pm25 <= 150) return STATUS_BANDS[3];
  if (pm25 <= 250) return STATUS_BANDS[4];
  return STATUS_BANDS[5];
}

